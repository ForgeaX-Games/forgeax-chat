export function translateStandaloneMessage(
	locale: StandaloneMessageLocale,
	key: string,
	vars?: Record<string, unknown>,
): string {
	const template =
		standaloneMessages[locale][key] ?? standaloneMessages.en[key] ?? key;
	if (!vars) return template;
	return template.replace(/\{\{?\s*(\w+)\s*\}?\}/g, (match, name: string) =>
		name in vars ? String(vars[name]) : match,
	);
}
